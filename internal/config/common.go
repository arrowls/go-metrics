// Package config содержит конфигурацию для сервера и агента метрик.
package config

const (
	// GaugeType определяет тип метрики как gauge (измеритель).
	// Gauge метрики представляют текущее значение, которое может увеличиваться и уменьшаться.
	GaugeType = "gauge"

	// CounterType определяет тип метрики как counter (счетчик).
	// Counter метрики только увеличиваются и представляют накопительное значение.
	CounterType = "counter"

	// HashHeaderName определяет имя HTTP заголовка для хеша подписи.
	// Используется для проверки целостности данных при передаче метрик.
	HashHeaderName = "HashSHA256"
)
